#!/usr/bin/env node
// Regenerates database/seed.sql from the app's bundled content in app/src/data,
// so the database and the app's offline fallback always start out identical.
//
//   node database/generate-seed.mjs        (Node 22.18+ — strips TypeScript types natively)

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { CURRENCIES, EMERGENCY, ESSENTIALS, ETIQUETTE, PHRASES } from '../app/src/data/guide.ts';
import { ITINERARIES } from '../app/src/data/itineraries.ts';
import { CATEGORIES, PLACES, REGIONS } from '../app/src/data/places.ts';

const here = dirname(fileURLToPath(import.meta.url));

function sql(value) {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'boolean') return value ? '1' : '0';
  if (typeof value === 'number') return String(value);
  return `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`;
}

function insert(table, columns, rows) {
  if (rows.length === 0) return '';
  const values = rows.map((row) => `  (${row.map(sql).join(', ')})`).join(',\n');
  return `INSERT INTO ${table} (${columns.join(', ')}) VALUES\n${values};\n`;
}

const out = [
  '-- Bali Guide seed data — generated by database/generate-seed.mjs. Do not edit by hand;',
  '-- change app/src/data/*.ts and regenerate, or edit rows directly in phpMyAdmin after import.',
  '',
  'SET NAMES utf8mb4;',
  'SET FOREIGN_KEY_CHECKS = 0;',
  ...[
    'itinerary_stops', 'itinerary_days', 'itineraries', 'place_tips', 'place_highlights', 'places',
    'regions', 'categories', 'phrases', 'guide_tips', 'emergency_contacts', 'currencies',
  ].map((table) => `TRUNCATE TABLE ${table};`),
  'SET FOREIGN_KEY_CHECKS = 1;',
  '',
];

out.push(
  insert(
    'categories',
    ['id', 'label', 'icon', 'color_from', 'color_to', 'sort_order'],
    CATEGORIES.map((c, i) => [c.id, c.label, c.icon, c.gradient[0], c.gradient[1], i]),
  ),
  insert(
    'regions',
    ['id', 'label', 'sort_order'],
    Object.entries(REGIONS).map(([id, label], i) => [id, label, i]),
  ),
  insert(
    'places',
    [
      'id', 'name', 'tagline', 'category_id', 'region_id', 'area', 'description', 'best_time',
      'hours', 'fee', 'duration', 'latitude', 'longitude', 'featured', 'sort_order',
    ],
    PLACES.map((p, i) => [
      p.id, p.name, p.tagline, p.category, p.region, p.area, p.description, p.bestTime,
      p.hours, p.fee, p.duration, p.coordinates.latitude, p.coordinates.longitude, Boolean(p.featured), i,
    ]),
  ),
  insert(
    'place_highlights',
    ['place_id', 'body', 'sort_order'],
    PLACES.flatMap((p) => p.highlights.map((body, i) => [p.id, body, i])),
  ),
  insert(
    'place_tips',
    ['place_id', 'body', 'sort_order'],
    PLACES.flatMap((p) => p.tips.map((body, i) => [p.id, body, i])),
  ),
  insert(
    'itineraries',
    ['id', 'title', 'summary', 'color_from', 'color_to', 'sort_order'],
    ITINERARIES.map((it, i) => [it.id, it.title, it.summary, it.gradient[0], it.gradient[1], i]),
  ),
);

// Days get explicit ids so their stops can reference them.
const days = [];
const stops = [];
ITINERARIES.forEach((it) => {
  it.days.forEach((day, dayIndex) => {
    const dayId = days.length + 1;
    days.push([dayId, it.id, day.title, dayIndex]);
    day.stops.forEach((stop, stopIndex) => stops.push([dayId, stop.placeId, stop.time, stop.note, stopIndex]));
  });
});

out.push(
  insert('itinerary_days', ['id', 'itinerary_id', 'title', 'sort_order'], days),
  insert('itinerary_stops', ['day_id', 'place_id', 'time_label', 'note', 'sort_order'], stops),
  insert(
    'currencies',
    ['code', 'label', 'per_unit_idr', 'sort_order'],
    CURRENCIES.map((c, i) => [c.code, c.label, c.perUnitIdr, i]),
  ),
  insert(
    'phrases',
    ['phrase', 'meaning', 'note', 'sort_order'],
    PHRASES.map((p, i) => [p.phrase, p.meaning, p.note ?? null, i]),
  ),
  insert(
    'guide_tips',
    ['section', 'icon', 'title', 'body', 'sort_order'],
    [
      ...ESSENTIALS.map((t, i) => ['essentials', t.icon, t.title, t.body, i]),
      ...ETIQUETTE.map((t, i) => ['etiquette', t.icon, t.title, t.body, i]),
    ],
  ),
  insert(
    'emergency_contacts',
    ['icon', 'label', 'number', 'sort_order'],
    EMERGENCY.map((e, i) => [e.icon, e.label, e.number, i]),
  ),
);

const target = join(here, 'seed.sql');
writeFileSync(target, out.join('\n'));
console.log(`Wrote ${target}: ${PLACES.length} places, ${ITINERARIES.length} itineraries.`);
